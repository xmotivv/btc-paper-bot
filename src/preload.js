'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bot', {
  state: () => ipcRenderer.invoke('state'),
  start: () => ipcRenderer.invoke('start'),
  stop: () => ipcRenderer.invoke('stop'),
  setStrategyEnabled: (id, on) => ipcRenderer.invoke('set-strategy-enabled', id, on),
  setStrategyParams: (id, params) => ipcRenderer.invoke('set-strategy-params', id, params),
  closePosition: (id) => ipcRenderer.invoke('close-position', id),
  closeAllPositions: () => ipcRenderer.invoke('close-all-positions'),
  liveConnect: (keyId, secretKey) => ipcRenderer.invoke('live-connect', keyId, secretKey),
  liveDisconnect: () => ipcRenderer.invoke('live-disconnect'),
  liveArm: () => ipcRenderer.invoke('live-arm'),
  liveDisarm: () => ipcRenderer.invoke('live-disarm'),
  liveKill: () => ipcRenderer.invoke('live-kill'),
  liveLimits: (patch) => ipcRenderer.invoke('live-limits', patch),
  setStrategyLive: (id, on) => ipcRenderer.invoke('set-strategy-live', id, on),
  setWebhook: (url) => ipcRenderer.invoke('webhook-set', url),
  testWebhook: () => ipcRenderer.invoke('webhook-test'),
  updateSettings: (patch) => ipcRenderer.invoke('update-settings', patch),
  reset: (cash) => ipcRenderer.invoke('reset', cash),
  exportCsv: () => ipcRenderer.invoke('export-csv'),
  openDataFolder: () => ipcRenderer.invoke('open-data-folder'),
  openUrl: (url) => ipcRenderer.invoke('open-url', url),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onEngine: (cb) => ipcRenderer.on('engine', (_e, v) => cb(v)),
  onUpdate: (cb) => ipcRenderer.on('update-status', (_e, v) => cb(v)),
});
